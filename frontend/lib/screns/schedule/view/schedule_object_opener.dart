import 'package:flutter/material.dart';

import '../models/schedule_row.dart';

/// Куда ведёт клик по строке ленты «Графики».
///
/// Отдельным интерфейсом, а не прямым вызовом: лента должна собираться в
/// тесте, а настоящий переход тянет за собой сетевые репозитории экрана
/// графика. Подставной вход в тесте — единственный способ проверить саму
/// ленту, не уходя в сеть.
///
/// Кто именно открывает, решает место встраивания: у админа своя реализация,
/// у прораба своя (`route_schedule_object_opener.dart`).
abstract class ScheduleObjectOpener {
  const ScheduleObjectOpener();

  /// Открыть экран «График» для строки [row].
  ///
  /// Контекст нужен, чтобы поставить маршрут: у экрана свой `Scaffold`, и он
  /// ложится поверх оболочки, а не подменяет её содержимое.
  ///
  /// Возвращаться нужно **как только экран показан**, а не когда его закрыли:
  /// лента на это время держит индикатор, и ожидание закрытия оставило бы её
  /// под ним на всё время просмотра графика.
  ///
  /// [onScheduleChanged] зовут, когда график объекта на экране поменялся —
  /// закрыли ТО, расставили год мастером. Лента под маршрутом жива и обновляет
  /// свою строку, не дожидаясь возврата: к тому времени, как человек нажмёт
  /// «назад», клетка уже верного цвета.
  Future<void> open(
    BuildContext context,
    ScheduleRow row, {
    VoidCallback? onScheduleChanged,
  });
}
