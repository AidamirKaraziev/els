import '../models/schedule_row.dart';

/// Куда ведёт клик по строке ленты «Графики».
///
/// Отдельным интерфейсом, а не прямым вызовом: экран графика живёт в оболочке
/// подрядчика и открывается сменой `IntTest.indexScreens` плюс четырьмя
/// загрузками в глобальные переменные. Знай об этом лента — её нельзя было бы
/// ни собрать в тесте, ни показать отдельно от оболочки.
///
/// Кто именно открывает, решает место встраивания: у админа своя реализация,
/// у прораба своя (`shell_schedule_object_opener.dart`).
abstract class ScheduleObjectOpener {
  const ScheduleObjectOpener();

  /// Подготовить данные объекта и переключить оболочку на экран «График».
  ///
  /// Возвращается **после** загрузок: лента держит на это время индикатор,
  /// иначе экран открывается пустым и дорисовывается на глазах.
  Future<void> open(ScheduleRow row);
}
