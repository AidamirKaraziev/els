import '../../../repository/schedules_repository.dart';
import '../models/schedule_wizard_data.dart';

/// Откуда мастер берёт заготовку годового графика.
///
/// Интерфейс, а не класс: под ним стоит либо фикстура, либо сеть. Экран и
/// блок при подмене не меняются.
abstract class ScheduleWizardRepository {
  /// Что ляжет в двенадцать месяцев года, если расставить график по программе.
  ///
  /// [anchorMonth] — месяц, на который приходится первая позиция программы.
  /// Не передан — сервер восстанавливает его по графику за прошлый год, а не
  /// восстановил, значит месяц должен назвать человек: тогда прилетает
  /// [ScheduleAnchorRequiredException].
  Future<ScheduleWizardData> preview(
    int objectId,
    int year, {
    int? anchorMonth,
  });

  /// Расставить год по программе — то же, что человек видел в предпросмотре.
  ///
  /// [anchorMonth] обязателен, в отличие от [preview]: месяц мастеру уже
  /// известен — либо сервер восстановил его по прошлому году, либо человек
  /// назвал сам. Дать серверу подобрать его во второй раз значило бы
  /// записать в базу не то, что показали на экране.
  ///
  /// Что именно легло в месяцы, здесь не возвращается: это спрашивают у ленты
  /// экрана объекта. Занятые месяцы ручка не трогает, и повторный вызов с
  /// теми же параметрами ничего не добавляет.
  Future<void> generate(
    int objectId,
    int year, {
    required int anchorMonth,
  });
}

/// Сервер не смог сам определить, с какого месяца идёт цикл.
///
/// Отдельным типом, а не проверкой кода 144 на месте: для мастера это не
/// поломка, а развилка работы — он показывает шаг «Точка отсчёта» и
/// спрашивает месяц. Плашкой с ошибкой такое показывать нечего.
class ScheduleAnchorRequiredException extends SchedulesException {
  const ScheduleAnchorRequiredException(String message) : super(message);
}

/// У модели объекта нет программы обслуживания.
///
/// Отдельным типом по той же причине, что и [ScheduleAnchorRequiredException]:
/// для мастера это не поломка, а развилка работы — он открывается со строкой
/// «программа не заведена» и предлагает её завести.
class ScheduleProgramMissingException extends SchedulesException {
  const ScheduleProgramMissingException(String message) : super(message);
}

/// Как экран объекта заводит репозиторий мастера.
///
/// Функцией, а не готовым объектом: сетевому репозиторию нужна модель
/// оборудования, а она известна только после загрузки карточки объекта — то
/// есть позже, чем строится сам экран.
typedef ScheduleWizardRepositoryBuilder = ScheduleWizardRepository Function(
  String modelName,
);
