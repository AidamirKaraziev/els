/// Ответственный за объект: прораб или механик.
///
/// Отдельной моделью, а не парой строк в карточке: на кадре это две
/// одинаковые плашки, и виджет у них один. Разными их делает только подпись.
class ScheduleResponsible {
  const ScheduleResponsible({
    required this.title,
    required this.fullName,
    this.id,
    this.photo,
  });

  /// Подпись слева в плашке: «Прораб», «Механик».
  final String title;

  /// Id сотрудника — по нему открывается его карточка. Может не приехать:
  /// объект отдаёт человека вложенным объектом, и старые записи приходят
  /// одним именем. Без id плашка просто не нажимается.
  final int? id;

  /// Как показано на кадре — инициалы и фамилия: «Н.В. Гоголевский».
  final String fullName;

  /// Путь к фотографии на сервере. Пустой или `null` — показываем заглушку;
  /// сотрудник без фото в базе обычное дело.
  final String? photo;
}
