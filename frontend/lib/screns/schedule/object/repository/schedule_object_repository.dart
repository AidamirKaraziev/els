import '../../models/month_cell.dart';
import '../models/schedule_object_card.dart';

/// Откуда экран берёт карточку объекта и его годовую ленту.
///
/// Интерфейс, а не класс: под ним стоит либо фикстура, либо сеть. Экран и
/// блок при подмене не меняются.
abstract class ScheduleObjectRepository {
  /// Карточка объекта: три верхних блока экрана целиком.
  Future<ScheduleObjectCard> fetchCard(int objectId);

  /// Двенадцать клеток года, январь..декабрь.
  ///
  /// Отдельным запросом от карточки: год человек переключает часто, а
  /// организация, адрес и ответственные от года не зависят — перезапрашивать
  /// их на каждую стрелку значит моргать всем экраном ради ленты.
  Future<List<MonthCell>> fetchYear(int objectId, int year);

  /// Перенести ТО с одного месяца на другой внутри года.
  ///
  /// Двигается не акт, а **ссылка на него в годовом плане**: месяц ТО — это
  /// колонка `<месяц>_to_id` в `planned_to`. Поэтому перенос — одно
  /// обновление плана: снять акт с прежнего месяца и положить на новый.
  ///
  /// Занятый месяц принимающей стороной быть не может — проверка стоит выше,
  /// в ленте, но и сервер молча чужой акт не затирает: он его заменит, и
  /// поэтому сюда нельзя приходить с занятым [toMonth].
  Future<void> moveCell(
    int objectId,
    int year, {
    required int actId,
    required int fromMonth,
    required int toMonth,
  });

  /// Расставить график на год по программе модели.
  ///
  /// Занятые месяцы ручка не трогает, повторный вызов ничего не добавляет.
  /// Ответ не разбираем: лента после создания перечитывается тем же
  /// [fetchYear], и состояния клеток считает сервер, а не мы по телу ответа.
  ///
  /// Якорь цикла здесь не передаётся — сервер подбирает его сам по прошлому
  /// году. Ради этого метод и уступил место мастеру: тот шлёт месяц, который
  /// человек видел в предпросмотре.
  @Deprecated(
    'График расставляет мастер: ScheduleWizardRepository.generate шлёт '
    'выбранный месяц. Метод оставлен живым — он в проде.',
  )
  Future<void> generateYear(int objectId, int year);
}
