/// Настройки, задаваемые при сборке приложения.
///
/// ## Почему не `.env`
///
/// Flutter компилируется в нативный код и в JS, и **никакого окружения в
/// рантайме у него нет**: на телефоне нет переменных окружения, а браузер их не
/// отдаёт. Штатный механизм Dart — константы из `--dart-define`, которые
/// подставляются на этапе компиляции:
///
/// ```
/// flutter build web --dart-define=API_ORIGIN=https://els.example.ru
/// flutter run --dart-define-from-file=env/local.json
/// ```
///
/// Пакет `flutter_dotenv` кладёт файл в ассеты приложения — то есть его видит
/// любой, кто распакует APK или откроет вкладку Network. Для секретов он не
/// годится, а для остального `--dart-define` проще и не падает в рантайме.
///
/// ## Правило про секреты
///
/// **В клиентском приложении секретов не бывает.** Всё, что попало в сборку —
/// публично: APK распаковывается, JS читается. Ключи внешних сервисов, пароли
/// и токены живут только на бэкенде, а приложение обращается к ним через наш
/// API. Поэтому здесь только адреса и настройки отображения.
///
/// Читается через `String.fromEnvironment` — обязательно `const`, иначе
/// значение не подставится на компиляции.
///
/// Адрес API живёт отдельно, в [ApiConfig] (`api_config.dart`): у него своя
/// логика — веб определяет его из origin страницы.
class AppConfig {
  /// Сервер тайлов карты.
  ///
  /// По умолчанию публичный OSM. Меняется, если поднимем свои тайлы или
  /// перейдём на платного провайдера — тогда это станет per-environment
  /// настройкой, ради которой механизм и нужен.
  static const mapTileUrl = String.fromEnvironment(
    'MAP_TILE_URL',
    defaultValue: 'https://tile.openstreetmap.org/{z}/{x}/{y}.png',
  );

  /// User-Agent для OSM: и тайлы, и геокодер Nominatim требуют опознаваемое
  /// приложение и блокируют анонимные запросы.
  ///
  /// TODO: заменить на финальный идентификатор приложения, когда он будет
  /// согласован с заказчиком (сейчас в `android/` стоит шаблонный
  /// `com.example.els`, с которым нельзя публиковаться в Google Play).
  static const osmUserAgent = String.fromEnvironment(
    'OSM_USER_AGENT',
    defaultValue: 'els-app (+https://tochkalift.ru)',
  );
}
