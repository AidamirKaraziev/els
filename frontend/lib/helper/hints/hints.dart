/// Карточка «С чего начать» на главной — своя под роль.
class StartHereContent {
  const StartHereContent({required this.title, required this.steps});

  final String title;
  final List<String> steps;
}

/// Что показать человеку в первый раз.
///
/// Разное по ролям: прорабу нужен график, клиенту — отчёт. Общий текст был бы
/// бесполезен обоим.
StartHereContent? startHereFor(int roleId) {
  switch (roleId) {
    case Roles.admin:
      return const StartHereContent(
        title: 'С чего начать',
        steps: <String>[
          'На главной — четыре виджета: просроченные ТО, выполнение графика, '
              'топ поломок и сотрудники. Цифры считаются за выбранный месяц.',
          'Раздел «Графики» — план ТО по объектам. Нажатие на месяц создаёт '
              'акт: так ТО и планируется.',
          'Раздел «Отчёты» — что делали на объектах за период, с выгрузкой в '
              'Excel и PDF для отправки клиенту.',
        ],
      );
    case Roles.foreman:
      return const StartHereContent(
        title: 'С чего начать',
        steps: <String>[
          'Заведите график ТО на текущий год в разделе «Графики»: нажатие на '
              'месяц создаёт акт, и объект попадает в план.',
          'После выезда откройте акт и нажмите «Завершить ТО» — пока акт не '
              'закрыт, работа считается невыполненной.',
          'Просроченные ТО на главной — это незакрытые акты за прошедшие '
              'месяцы. По ним видно, где долг.',
        ],
      );
    case Roles.client:
      return const StartHereContent(
        title: 'С чего начать',
        steps: <String>[
          'В разделе «Отчёты» видно, что делали на ваших объектах за период: '
              'плановые ТО, аварийные выезды и ваши заявки.',
          'Отчёт можно выгрузить в PDF или Excel за любой период — год, '
              'квартал или произвольные даты.',
          'Клик по строке объекта показывает подробности: что именно было '
              'сделано в рамках каждой работы.',
        ],
      );
    default:
      return null;
  }
}
