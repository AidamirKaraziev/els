/// Тексты всех подсказок в одном месте.
///
/// Реестр, а не строки по коду: тексты правит человек, который пишет их
/// голосом продукта, а не ищет по семидесяти тысячам строк чужого фронта.
/// Виджету достаточно идентификатора.
///
/// Подсказка ставится только там, где есть **настоящая неявность** — вещь,
/// которую невозможно вывести из интерфейса. Объяснять подписью кнопку
/// «Сохранить» не нужно: от этого подсказки перестают читать все.

/// Короткое пояснение у значка «?».
class Hint {
  const Hint({required this.title, required this.body});

  final String title;
  final String body;
}

