import 'package:flutter/foundation.dart' show kIsWeb;

/// Единственное место, которое знает адрес бэкенда.
///
/// Раньше адрес лежал в `IntTest.myIp` — в файле с цветами — и подставлялся
/// в 185 строк интерполяцией с жёстко зашитой схемой `http`. Поменять окружение
/// можно было только правкой кода и пересборкой.
///
/// Кто какой адрес получает:
///
/// * **веб** — тот же origin, откуда отдана страница. nginx отдаёт и приложение,
///   и API, поэтому одна и та же сборка работает и на `localhost:8080`,
///   и на боевом домене, и по HTTPS — без пересборки и без CORS.
/// * **iOS / Android** — из `--dart-define`, потому что телефону нужен адрес
///   машины в сети:
///   `flutter run --dart-define=API_ORIGIN=http://192.168.1.5:8080`
///   (Android-эмулятор: `http://10.0.2.2:8080`).
class ApiConfig {
  /// Задаётся при сборке: `--dart-define=API_ORIGIN=http://host:port`.
  /// Пустая строка означает «не задано» — const-строки не бывают null.
  static const _originOverride = String.fromEnvironment('API_ORIGIN');

  /// Куда идёт мобильная сборка, если `API_ORIGIN` не задан.
  ///
  /// Раньше здесь стоял `http://185.154.193.42:8000` — стенд прежнего
  /// подрядчика. Веб на него не попадал (там origin берётся из страницы), а
  /// APK попадал: первая же сборка для механиков стучалась на мёртвый адрес и
  /// показывала «сервер недоступен». Боевой домен — единственный разумный
  /// ответ на вопрос «куда, если не сказали».
  ///
  /// Сборки в CI всё равно передают адрес явно, `--dart-define=API_ORIGIN`.
  static const _defaultOrigin = 'https://els23.ru';

  /// Схема, хост и порт бэкенда, без завершающего слэша.
  static String get origin {
    if (_originOverride.isNotEmpty) return _originOverride;
    if (kIsWeb) return Uri.base.origin;
    return _defaultOrigin;
  }

  /// Префикс REST API. Именно его подставляют в запросы.
  static String get base => '$origin/api/v1';

  /// Схема для ссылок на файлы.
  ///
  /// Бэкенд отдаёт путь к фото и сканам без схемы — `host:port/api/v1/static/…`
  /// (см. `backend/src/getters/static_url.py`), и клиент дописывает её сам.
  /// Раньше в 111 местах было зашито `'http://'`. Под HTTPS браузер считает
  /// такую картинку смешанным контентом и блокирует — то есть в день включения
  /// сертификата разом пропали бы все аватарки, сканы документов и фото
  /// объектов.
  ///
  /// На вебе берём схему той страницы, которая открыта: приложение и API
  /// живут на одном origin, значит и файлы тоже. На телефоне — схему из
  /// `API_ORIGIN`, потому что там страницы нет.
  static String get scheme {
    final String value = kIsWeb ? Uri.base.scheme : Uri.parse(origin).scheme;
    return value.isEmpty ? 'http' : value;
  }

  /// Адрес из ответа сервера, пригодный для `launchUrl` и `NetworkImage`.
  ///
  /// Бэкенд отдаёт адреса файлов и ссылок на скачивание **без схемы** —
  /// `els23.ru/api/v1/static/…?token=…` (см. `getters/static_url.py` и
  /// `POST /files/link`). Строка без схемы для браузера — относительный путь:
  /// он приклеивается к текущей странице, и получается
  /// `https://els23.ru/els23.ru/api/v1/…` — файл молча не открывается.
  /// На проде так пропала ссылка на PDF дефектного акта: три соседние
  /// выгрузки схему дописывали каждая у себя, четвёртая — нет.
  ///
  /// Через эту функцию проходит любой `url`, пришедший с сервера. Уже
  /// абсолютный адрес остаётся как есть.
  static String withScheme(String url) =>
      url.contains('://') ? url : '$scheme://$url';
}
