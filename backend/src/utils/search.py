"""Поиск свободным текстом по колонкам.

Живёт рядом с пагинацией и по той же причине: это не логика какой-то одной
ручки, а приём, который повторится в каждом списке с лупой. Первый
пользователь — лента графиков ТО.

Главное здесь — экранирование. В `LIKE` символы `%` и `_` значат «что
угодно» и «любой один символ», и человек, который ищет объект «ТО_1», без
экранирования получил бы заодно «ТО-1» и «ТО 1», а одинокий `%` в строке
поиска снял бы отбор целиком. Поэтому спецсимволы в введённом тексте
экранируются, а каждому `ilike` передаётся `escape`.
"""

from typing import Optional

from sqlalchemy import or_

#: Символ экранирования для `LIKE`. Обратный слэш, как в самом SQL.
_ESCAPE = "\\"


def like_escape(text: str) -> str:
    """Спецсимволы `LIKE` внутри введённого текста — обычными символами.

    Сам `_ESCAPE` заменяется первым: иначе его подставленные копии попали бы
    под замену следующих строк ещё раз.
    """
    for char in (_ESCAPE, "%", "_"):
        text = text.replace(char, _ESCAPE + char)
    return text


def ilike_any(text: Optional[str], *columns):
    """Условие «текст встречается хотя бы в одной из колонок».

    Регистр не важен: искать «спортмастер» и не находить «Спортмастер» —
    не поиск. Пустой текст даёт `None`, а не условие «совпадает со всем»:
    вызывающий обязан отличить «не искали» от «искали и не нашли».
    """
    if text is None:
        return None

    text = text.strip()
    if not text:
        return None

    pattern = f"%{like_escape(text)}%"
    return or_(*[column.ilike(pattern, escape=_ESCAPE) for column in columns])
