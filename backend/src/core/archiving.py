"""Мягкое удаление: запись не исчезает, а уходит в архив.

Настоящего `DELETE` в системе почти нет и не должно быть. Причина не в
бережливости, а в офлайн-клиенте: телефон механика синхронизируется вопросом
«что изменилось с момента T», и удалённая строка на такой вопрос не отвечает
ничем — она просто перестаёт приходить, и на телефоне остаётся навсегда.
Заархивированная строка приходит с `is_actual=false`, и клиент знает, что её
надо убрать.

Отсюда три вида выборки:

* `ACTUAL` — по умолчанию. Обычные списки: удалённого в них не видно.
* `ARCHIVED` — отдельный вид «удалённое», куда заказчик идёт смотреть архив и
  откуда запись можно вернуть.
* `ALL` — синхронизация. `changed_since` обязан отдавать и архивные, иначе
  смысл метки теряется.

Фильтр применяется в CRUD, рядом с областью видимости, и по той же причине:
забытый фильтр не падает и не ругается, просто в списке оказывается лишнее.

Статистика и отчёты архив пока **считают**: там речь о работе, которая была
сделана, а не о списке записей, и решения «выкидывать ли из цифр удалённое»
заказчик ещё не принимал. Место, где это решается, — здесь.
"""

from enum import Enum


class ArchiveView(str, Enum):
    """Какие записи нужны выборке."""

    #: Только живые. Так работают все списки, если не сказано иного.
    ACTUAL = "actual"
    #: Только архив — отдельный вид.
    ARCHIVED = "archived"
    #: И те и другие. Только для синхронизации офлайн-клиента.
    ALL = "all"

    @classmethod
    def choose(cls, *, only_archived: bool = False, syncing: bool = False):
        """Вид выборки по параметрам ручки.

        Синхронизация перебивает всё: клиенту, который спрашивает «что
        изменилось», архивные записи нужны именно затем, чтобы узнать об
        удалении.
        """
        if syncing:
            return cls.ALL
        return cls.ARCHIVED if only_archived else cls.ACTUAL


def archive_filter(model, view: ArchiveView = ArchiveView.ACTUAL):
    """SQL-условие «эта запись подходит под вид выборки».

    Живым считается всё, что не помечено архивным явно: колонка добавлена
    миграцией со значением по умолчанию, но записи, заведённые в обход модели,
    могут остаться с `NULL`, и терять их в списках нельзя.
    """
    if view is ArchiveView.ARCHIVED:
        return model.is_actual.is_(False)
    return model.is_actual.isnot(False)


def apply_archive_view(query, model, view: ArchiveView = ArchiveView.ACTUAL):
    """Тот же фильтр, но сразу на запрос. `ALL` не фильтрует вовсе."""
    if view is ArchiveView.ALL:
        return query
    return query.filter(archive_filter(model, view))
